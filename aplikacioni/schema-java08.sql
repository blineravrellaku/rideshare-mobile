CREATE TABLE IF NOT EXISTS kerkesat (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  udhetim_id TEXT NOT NULL REFERENCES udhetimet(id),
  udhetar_id TEXT NOT NULL REFERENCES profilet(github_id),
  status TEXT NOT NULL DEFAULT 'ne_pritje'
    CHECK (status IN ('ne_pritje', 'pranuar', 'refuzuar')),
  krijuar_me TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (udhetim_id, udhetar_id)
);

CREATE INDEX IF NOT EXISTS kerkesat_udhetim_status_idx
  ON kerkesat (udhetim_id, status, krijuar_me);

CREATE OR REPLACE FUNCTION krijo_kerkese(
  p_udhetim_id TEXT,
  p_udhetar_id TEXT
) RETURNS TEXT
LANGUAGE plpgsql
AS $$
DECLARE
  v_id BIGINT;
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM profilet WHERE github_id = p_udhetar_id
  ) THEN
    RETURN 'ndaluar';
  END IF;

  PERFORM 1
  FROM udhetimet
  WHERE id = p_udhetim_id
    AND shofer_id IS DISTINCT FROM p_udhetar_id
    AND vende > 0
  FOR UPDATE;

  IF NOT FOUND THEN
    IF NOT EXISTS (SELECT 1 FROM udhetimet WHERE id = p_udhetim_id) THEN
      RETURN 'udhetim';
    END IF;
    IF EXISTS (
      SELECT 1 FROM udhetimet
      WHERE id = p_udhetim_id AND shofer_id = p_udhetar_id
    ) THEN
      RETURN 'vetvetja';
    END IF;
    RETURN 'pa_vende';
  END IF;

  INSERT INTO kerkesat (udhetim_id, udhetar_id)
  SELECT u.id, p_udhetar_id
  FROM udhetimet AS u
  WHERE u.id = p_udhetim_id
    AND u.shofer_id IS DISTINCT FROM p_udhetar_id
    AND u.vende > 0
  ON CONFLICT (udhetim_id, udhetar_id) DO NOTHING
  RETURNING id INTO v_id;

  IF v_id IS NOT NULL THEN
    RETURN 'derguar';
  END IF;
  IF EXISTS (
    SELECT 1 FROM kerkesat
    WHERE udhetim_id = p_udhetim_id AND udhetar_id = p_udhetar_id
  ) THEN
    RETURN 'ekziston';
  END IF;
  RETURN 'pa_vende';
END;
$$;

CREATE OR REPLACE FUNCTION prano_kerkese(
  p_kerkese_id BIGINT,
  p_shofer_id TEXT
) RETURNS TEXT
LANGUAGE plpgsql
AS $$
DECLARE
  v_udhetim_id TEXT;
BEGIN
  SELECT k.udhetim_id INTO v_udhetim_id
  FROM kerkesat AS k
  WHERE k.id = p_kerkese_id AND k.status = 'ne_pritje';

  IF NOT FOUND THEN
    RETURN 'jo_ne_pritje';
  END IF;

  PERFORM 1 FROM udhetimet
  WHERE id = v_udhetim_id AND shofer_id = p_shofer_id
  FOR UPDATE;
  IF NOT FOUND THEN
    RETURN 'ndaluar';
  END IF;

  PERFORM 1 FROM kerkesat
  WHERE id = p_kerkese_id
    AND udhetim_id = v_udhetim_id
    AND status = 'ne_pritje'
  FOR UPDATE;
  IF NOT FOUND THEN
    RETURN 'jo_ne_pritje';
  END IF;

  UPDATE udhetimet
  SET vende = vende - 1
  WHERE id = v_udhetim_id AND vende > 0;
  IF NOT FOUND THEN
    RETURN 'pa_vende';
  END IF;

  UPDATE kerkesat SET status = 'pranuar'
  WHERE id = p_kerkese_id;
  RETURN 'pranuar';
END;
$$;

CREATE OR REPLACE FUNCTION refuzo_kerkese(
  p_kerkese_id BIGINT,
  p_shofer_id TEXT
) RETURNS TEXT
LANGUAGE plpgsql
AS $$
BEGIN
  UPDATE kerkesat AS k
  SET status = 'refuzuar'
  FROM udhetimet AS u
  WHERE k.id = p_kerkese_id
    AND k.udhetim_id = u.id
    AND k.status = 'ne_pritje'
    AND u.shofer_id = p_shofer_id;

  IF FOUND THEN
    RETURN 'refuzuar';
  END IF;
  IF EXISTS (
    SELECT 1 FROM kerkesat
    WHERE id = p_kerkese_id AND status = 'ne_pritje'
  ) THEN
    RETURN 'ndaluar';
  END IF;
  RETURN 'jo_ne_pritje';
END;
$$;
